"""Ember's effect art (public/game/fx, public/game/effects) as sprite clips, and the battle pack's manifest.

Writes content/fx.sprites.json: one set "fx", one clip per image. A "...-4x4" sheet becomes 16 frames (its cells,
row by row); any other image one frame. Art painted on black (no alpha channel) is cooked with "!black" (alpha =
its brightest channel, as Ember's deriveAlphaFromBlack). Clip name = file name without extension.

Then merges content/units.sprites.json + content/decor.sprites.json + content/fx.sprites.json into
build/sprites/battle.sprites.json (the one pack the game mounts: two packs would both define sprites/roster).

  python -I tools/scripts/fx_sprites.py [content/assets/game]
Ember is only read.
"""
import json
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GAME = sys.argv[1] if len(sys.argv) > 1 else "content/assets/game"


def clips():
    out = []
    for folder in ("fx", "effects"):
        for name in sorted(os.listdir(os.path.join(GAME, folder))):
            stem, ext = os.path.splitext(name)
            if ext.lower() not in (".png", ".jpg", ".jpeg", ".webp"):
                continue
            rel = f"{folder}/{name}"
            with Image.open(os.path.join(GAME, folder, name)) as im:
                black = "A" not in im.getbands()
            suffix = "!black" if black else ""
            if "4x4" in stem:
                frames = {"list": [f"{rel}#4x4:{i}{suffix}" for i in range(16)]}
            else:
                frames = {"file": rel + suffix}
            out.append({"name": stem, "pack": "fx", "mode": "once", "fps": 24.0, "frames": frames})
    return out


# The Spells menu's groups (apps/sandbox/SpellsMenu.h addLoose): file-name prefix -> group, first match wins. Keep the
# two in step: the menu's numbers ("Arcano 01") come from this order.
GROUPS = [("arcane", "Arcano"), ("ember", "Brasa"), ("fireball", "Bola de Fogo"), ("fire", "Fogo"), ("frost", "Gelo"),
          ("holy", "Sagrado"), ("lightning", "Raio"), ("poison", "Veneno"), ("caustic", "Veneno Cáustico"),
          ("shadow", "Sombra"), ("warp-portal", "Portal (arte)"), ("warp", "Portal"), ("arrow", "Flecha"),
          ("impact", "Impacto"), ("blizzard", "Nevasca"), ("webfloor", "Teia")]


def effects_list(fx_clips):
    """content/fx/effects-list.md: every loose effect's menu number, its file in Ember, its frames."""
    groups = {}
    for c in fx_clips:
        name = next((label for prefix, label in GROUPS if c["name"].startswith(prefix)), "Outros")
        groups.setdefault(name, []).append(c)
    lines = ["# Efeitos soltos: every effect image, numbered as the Spells menu shows it",
             "",
             "Generated by `python -I tools/scripts/fx_sprites.py` from Ember's `public/game/fx` and `public/game/effects`",
             "(cooked into the battle pack, sprite set `fx`, clip = file name without extension). The menu's",
             "\"Efeitos soltos\" plays each one alone. Numbers are fixed by this order; new art is added at the end of",
             "its group, never renumbered.",
             ""]
    for name, items in groups.items():
        lines += [f"## {name}", "", "| Menu | File | Frames |", "|---|---|---|"]
        for i, c in enumerate(items, 1):
            f = c["frames"]
            src = (f.get("file") or f["list"][0]).split("#")[0].split("!")[0]
            n = len(f["list"]) if "list" in f else 1
            lines.append(f"| {name} {i:02} | `{src}` | {n} |")
        lines.append("")
    return "\n".join(lines)


def main():
    fx = {"version": 1, "sets": [{"name": "fx", "clips": clips()}]}
    os.makedirs(os.path.join(ROOT, "content", "fx"), exist_ok=True)
    with open(os.path.join(ROOT, "content", "fx", "effects-list.md"), "w", encoding="utf-8") as f:
        f.write(effects_list(fx["sets"][0]["clips"]))
    with open(os.path.join(ROOT, "content", "fx.sprites.json"), "w", encoding="utf-8") as f:
        json.dump(fx, f, indent=1, ensure_ascii=False)
        f.write("\n")
    sets = []
    for part in ("ember", "decor", "fx"):
        with open(os.path.join(ROOT, "content", f"{part}.sprites.json"), encoding="utf-8") as f:
            sets += json.load(f)["sets"]
    # The decorations come from the repo's decoracoes-2d/ (tools/scripts/sprites/decor_folder.py), not Ember's root.
    for s in sets:
        for c in s["clips"] if s["name"] == "decor" else []:
            f = c["frames"]
            if "list" in f:
                f["list"] = [ROOT.replace("\\", "/") + "/" + p if p.startswith("decoracoes-2d/") else p for p in f["list"]]
    os.makedirs(os.path.join(ROOT, "build", "sprites"), exist_ok=True)
    with open(os.path.join(ROOT, "build", "sprites", "battle.sprites.json"), "w", encoding="utf-8") as f:
        json.dump({"version": 1, "sets": sets}, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(f"fx: {len(fx['sets'][0]['clips'])} clips; battle manifest: {len(sets)} sets")


if __name__ == "__main__":
    main()
